# ── Endpoints ─────────────────────────────────────────────────────────────────

@router.get("", response_model=BattlesResponse)
async def list_battles(
    category: Optional[str] = Query(None, description="Filter by category (Ancient, Medieval, etc.)"),
    sort: Optional[str] = Query("chronological", description="Sort: chronological, casualties, impact"),
):
    filtered = BATTLES
    if category:
        filtered = [b for b in filtered if b.category.lower() == category.lower()]

    if sort == "impact":
        filtered = sorted(filtered, key=lambda b: b.impact_score, reverse=True)
    elif sort == "chronological":
        filtered = sorted(filtered, key=lambda b: b.year)
    # casualties sort is done client-side since the field is a string

    return BattlesResponse(battles=filtered, total=len(filtered))


@router.get("/{slug}")
async def get_battle(slug: str):
    for b in BATTLES:
        if b.slug == slug:
            return b
    return {"error": "Battle not found"}
