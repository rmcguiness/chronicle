"""
Battles router — serves curated data on history's most decisive battles.

GET /api/battles          → list all battles (with optional filters)
GET /api/battles/:slug    → single battle detail
"""
from __future__ import annotations

from typing import Optional

from fastapi import APIRouter, Query
from pydantic import BaseModel

router = APIRouter(prefix="/api/battles", tags=["battles"])


# ── Data model ────────────────────────────────────────────────────────────────

class BattleItem(BaseModel):
    slug: str
    name: str
    year: int
    year_display: str
    location: str
    country_emoji: str
    side_a: str
    side_b: str
    outcome: str
    winner: str
    casualties: str
    significance: str
    decisive_factor: str
    category: str  # Ancient / Medieval / Early Modern / Modern / Naval / Siege
    impact_score: int  # 1–10 editorial score
    chronicle_query: str


class BattlesResponse(BaseModel):
    battles: list[BattleItem]
    total: int


