router = APIRouter(prefix="/api/battles", tags=["battles"])


# ── Data models ──────────────────────────────────────────────────────────────


class Commander(BaseModel):
    name: str
    side: str  # "A" or "B"


class BattleItem(BaseModel):
    slug: str
    name: str
    year: int
    is_bce: bool
    date_display: str
    location: str
    flag_emoji: str
    era: str
    region: str
    side_a: str
    side_b: str
    commanders: list[Commander]
    troops_a: str
    troops_b: str
    outcome: str
    victor: str
    why_it_mattered: str
    butterfly_effect: str
    decisiveness: int
    changed_everything: bool
    chronicle_query: str
    db_event_count: int = 0
    db_event_slugs: list[str] = []


class BattlesResponse(BaseModel):
    battles: list[BattleItem]
    total: int
    total_db_events: int = 0


