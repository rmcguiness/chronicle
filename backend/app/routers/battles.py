@router.get("", response_model=BattlesResponse)
async def list_battles(db: AsyncSession = Depends(get_db)):
    """Return all 25 decisive battles, enriched with DB event cross-references."""

    total_db = 0
    for b in BATTLES:
        stmt = select(Event.slug).where(
            Event.review_status == "approved",
            or_(
                Event.title.ilike(f"%{b.chronicle_query}%"),
                Event.slug.ilike(f"%{b.slug}%"),
            ),
        )
        result = await db.execute(stmt)
        slugs = [r[0] for r in result.all()]
        b.db_event_count = len(slugs)
        b.db_event_slugs = slugs
        total_db += len(slugs)

    return BattlesResponse(
        battles=BATTLES,
        total=len(BATTLES),
        total_db_events=total_db,
    )
